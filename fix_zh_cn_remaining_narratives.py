def main() -> int:
    fixed = 0
    for pillar, idx_map in FIXES.items():
        path = DATA / "zh_cn" / "core_pillars" / f"{pillar}.json"
        if not path.exists():
            print(f"[SKIP] {pillar}.json not found")
            continue
        d = json.loads(path.read_text(encoding="utf-8"))
        narr = d.get("narrative", [])
        changed = False
        for idx, text in idx_map.items():
            if idx >= len(narr):
                print(f"[WARN] {pillar}: narrative[{idx}] out of range")
                continue
            if narr[idx] == text:
                print(f"[OK]   {pillar}[{idx}] already fixed")
                continue
            narr[idx] = text
            changed = True
            fixed += 1
        if changed:
            path.write_text(
                json.dumps(d, ensure_ascii=False, indent=2) + "\n",
                encoding="utf-8",
            )
            print(f"[FIX]  {pillar}")
    return fixed


if __name__ == "__main__":
    n = main()
    print(f"\nTotal fixed: {n} paragraphs")