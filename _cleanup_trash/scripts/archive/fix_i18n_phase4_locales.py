def deep_merge(base: dict, override: dict) -> dict:
    """override의 값으로 base를 재귀적으로 덮어씀."""
    for k, v in override.items():
        if isinstance(v, dict) and isinstance(base.get(k), dict):
            deep_merge(base[k], v)
        else:
            base[k] = v
    return base


def process_lang(lang: str) -> bool:
    path = LOCALES / f"{lang}.json"
    if not path.exists():
        print(f"  [ERR] {path.name} 없음")
        return False
    data = json.loads(path.read_text(encoding="utf-8"))
    before = json.dumps(data, sort_keys=True, ensure_ascii=False)
    deep_merge(data, TRANSLATIONS[lang])
    after = json.dumps(data, sort_keys=True, ensure_ascii=False)
    if before == after:
        print(f"  [SKIP] {path.name} 이미 번역 반영됨")
        return True
    path.write_text(
        json.dumps(data, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    print(f"  [OK] {path.name} 업데이트")
    return True


def verify() -> bool:
    print("\n[verify] 로드 및 스팟체크")
    ok = True
    for lang, samples in (
        ("ja", {"tabs.home": "ホーム", "sections.yourCore": "あなたの本質"}),
        ("zh_cn", {"tabs.home": "首页", "sections.yourCore": "你的核心"}),
        ("es", {"tabs.home": "Inicio", "sections.yourCore": "Tu Núcleo"}),
    ):
        data = json.loads((LOCALES / f"{lang}.json").read_text(encoding="utf-8"))
        for dotted, expected in samples.items():
            a, b = dotted.split(".")
            actual = data.get(a, {}).get(b)
            if actual == expected:
                print(f"  [OK] {lang}/{dotted} = {expected!r}")
            else:
                print(f"  [ERR] {lang}/{dotted}: expected {expected!r}, got {actual!r}")
                ok = False
    return ok


def main() -> int:
    print("=" * 60)
