def main() -> int:
    print("=" * 60)
    print("[Phase 3-8 — JA] core_pillars Earth/戊 (6 files)")
    print("=" * 60)

    if not JA.exists():
        print(f"[ERR] {JA} 없음")
        return 1

    for pillar, trans in TRANSLATIONS.items():
        fpath = JA / f"{pillar}.json"
        if not fpath.exists():
            print(f"[ERR] {fpath.name} 없음")
            return 1
        data = json.loads(fpath.read_text(encoding="utf-8"))
        data.update(trans)
        payload = json.dumps(data, ensure_ascii=False, indent=2) + "\n"
        try:
            json.loads(payload)
        except json.JSONDecodeError as e:
            print(f"[ERR] {pillar}: JSON 검증 실패 ({e})")
            return 1
        fpath.write_text(payload, encoding="utf-8")
        print(f"✅ {pillar}: {trans['name']}")

    print(f"\n✅ {len(TRANSLATIONS)}개 파일 저장 완료")

    # ---- verify ----
    print("\n[verify]")
    ok = True
    for pillar, trans in TRANSLATIONS.items():
        data = json.loads((JA / f"{pillar}.json").read_text(encoding="utf-8"))
        if data.get("name") != trans["name"]:
            print(f"  [ERR] {pillar}.name mismatch: {data.get('name')!r}")
            ok = False
        else:
            print(f"  [OK] {pillar}.name = {data['name']}")
        if not KANA_RE.search(data.get("hero", "")):
            print(f"  [ERR] {pillar}.hero not Japanese: {data.get('hero', '')[:50]!r}")
            ok = False
        else:
            print(f"  [OK] {pillar}.hero Japanese")
        if len(data.get("narrative", [])) != 4:
            print(f"  [ERR] {pillar}.narrative count = {len(data.get('narrative', []))}")
            ok = False
        else:
            print(f"  [OK] {pillar}.narrative 4개")

    checks = [
        ("庚午", True, "Metal/庚 회귀 방지"),
        ("己丑", True, "Earth/己 회귀 방지"),
        ("壬子", True, "Water/壬 회귀 방지"),
        ("癸亥", False, "癸 영어 유지 (3-9 대상, 의도)"),
        ("辛酉", False, "辛 영어 유지 (3-10 대상, 의도)"),
        ("甲子", True, "Wood 회귀 방지"),
    ]
    for pillar, should_be_ja, label in checks:
        p = JA / f"{pillar}.json"
        if not p.exists():
            print(f"  [WARN] {pillar}.json 없음 — {label} 스킵")
            continue
        data = json.loads(p.read_text(encoding="utf-8"))
        is_ja = bool(KANA_RE.search(data.get("hero", "")))
        if is_ja == should_be_ja:
            print(f"  [OK] {label}")
        else:
            print(f"  [WARN] {label} 상태 불일치 (is_ja={is_ja})")

    print()
    if ok:
        print("[Phase 3-8 OK] 다음:")
        print("  python -m pytest -q")
        print('  git add -A; git commit -m "i18n(ja): core_pillars earth/戊 (6)"')
        return 0
    print("[Phase 3-8 FAIL] 위 로그 확인")
    return 1


if __name__ == "__main__":
    sys.exit(main())