def _is_ja(s: str) -> bool:
    return bool(s) and bool(KANA_RE.search(s))


def verify() -> bool:
    print("\n[verify]")
    data = json.loads(JA_COMPAT.read_text(encoding="utf-8"))
    ok = True
    tags = ("STEM_UNION", "STEM_CLASH", "BRANCH_UNION", "BRANCH_CLASH",
            "TEN_GOD_FRIEND", "TEN_GOD_WEALTH", "TEN_GOD_OFFICER",
            "TEN_GOD_OUTPUT", "TEN_GOD_RESOURCE", "MIXED")
    for rel in ("romance", "business"):
        for tag in tags:
            e = data.get("DAY_MASTER_CONTENT", {}).get(rel, {}).get(tag, {})
            if not (_is_ja(e.get("headline", "")) and _is_ja(e.get("body", ""))):
                print(f"  [ERR] DAY_MASTER_CONTENT.{rel}.{tag}")
                ok = False
    if ok:
        print("  [OK] DAY_MASTER_CONTENT romance/business 全タグ = JA (20/20)")
    return ok


def main() -> int:
    print("=" * 60)
    print("[Phase 4-2] JA compatibility — DAY_MASTER_CONTENT (romance/business)")
    print("=" * 60)
    if not JA_COMPAT.exists():
        print(f"❌ 파일 없음: {JA_COMPAT}"); return 1

    data = json.loads(JA_COMPAT.read_text(encoding="utf-8"))
    for rel in ("romance", "business"):
        data.setdefault("DAY_MASTER_CONTENT", {}).setdefault(rel, {}).update(T[rel])

    payload = json.dumps(data, ensure_ascii=False, indent=2) + "\n"
    json.loads(payload)
    JA_COMPAT.write_text(payload, encoding="utf-8")
    print("✅ 저장 완료")

    ok = verify()
    print("=" * 60)
    if not ok:
        print("❌ verify 실패"); return 1
    print("🎉 Phase 4-2 완료")
    return 0


