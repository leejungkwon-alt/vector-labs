def _ja(s): return bool(s) and bool(KANA_RE.search(s))

def main():
    print("=" * 60); print("[Phase 4-3] compat friend/family"); print("=" * 60)
    if not JA.exists(): print(f"❌ {JA}"); return 1
    data = json.loads(JA.read_text(encoding="utf-8"))
    for rel in ("friend", "family"):
        data.setdefault("ELEMENT_CONTENT", {}).setdefault(rel, {}).update(ELEM[rel])
        data.setdefault("DAY_MASTER_CONTENT", {}).setdefault(rel, {}).update(DAY[rel])
    payload = json.dumps(data, ensure_ascii=False, indent=2) + "\n"
    json.loads(payload)
    JA.write_text(payload, encoding="utf-8")
    print("✅ 저장 완료")

    # verify
    print("\n[verify]")
    ok = True
    for key, tags, rels in [
        ("ELEMENT_CONTENT", ("COMPLEMENTARY","BALANCED","MODERATE","TENSION","DEFAULT"), ("friend","family")),
        ("DAY_MASTER_CONTENT", ("COMPLEMENTARY","BALANCED","MODERATE","TENSION","DEFAULT"), ("friend","family")),
    ]:
        for rel in rels:
            for tag in tags:
                e = data[key][rel][tag]
                if not (_ja(e.get("headline","")) and _ja(e.get("body",""))):
                    print(f"  [ERR] {key}.{rel}.{tag}"); ok = False
    if ok:
        print("  [OK] ELEMENT/DMA friend+family = JA (20/20)")
    print("=" * 60)
    return 0 if ok else 1

if __name__ == "__main__": sys.exit(main())