def load_json(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def save_json(path: Path, data: dict) -> None:
    payload = json.dumps(data, ensure_ascii=False, indent=2) + "\n"
    json.loads(payload)
    path.write_text(payload, encoding="utf-8")


def main() -> int:
    print("=" * 60)
    print("[Phase 3-2 — JA] core_pillars Wood/乙 (6 files)")
    print("=" * 60)

    if not JA_DIR.exists():
        print(f"❌ {JA_DIR} 없음")
        return 1

    written = []
    for key, ov in TRANSLATIONS.items():
        path = JA_DIR / f"{key}.json"
        if not path.exists():
            print(f"❌ {key}.json 없음")
            return 1
        data = load_json(path)
        if data.get("pillar") != key:
            print(f"❌ {key}.json::pillar 필드 불일치 ({data.get('pillar')!r})")
            return 1
        old_name_trad = data.get("name_traditional", "")
        for k, v in ov.items():
            data[k] = v
        if "name_traditional" in data and data["name_traditional"] != old_name_trad:
            print(f"❌ {key}: name_traditional 손상")
            return 1
        save_json(path, data)
        print(f"✅ {key}: {ov['name']}")
        written.append(key)

    print(f"\n✅ {len(written)}개 파일 저장 완료")

    # ── 검증
    print("\n[verify]")
    ok = True
    for key, ov in TRANSLATIONS.items():
        data = load_json(JA_DIR / f"{key}.json")
        if data.get("name") == ov["name"]:
            print(f"  [OK] {key}.name = {data['name']}")
        else:
            print(f"  [ERR] {key}.name = {data.get('name')!r}")
            ok = False
        has_jp = any("\u3040" <= ch <= "\u30ff" or "\u4e00" <= ch <= "\u9fff" for ch in data.get("hero", ""))
        if has_jp:
            print(f"  [OK] {key}.hero Japanese")
        else:
            print(f"  [ERR] {key}.hero not Japanese")
            ok = False
        if len(data.get("narrative", [])) == 4:
            print(f"  [OK] {key}.narrative 4개")
        else:
            print(f"  [ERR] {key}.narrative {len(data.get('narrative', []))}개")
            ok = False

