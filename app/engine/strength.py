# app/engine/strength.py
"""
일간의 신강/신약 판정 (억부 기준).

억부론: 일간(day master)이 사주 안에서 얼마나 힘을 받는가?
- 신강: 일간이 강함 → 洩(식상)·耗(재성)·剋(관성)으로 균형
- 신약: 일간이 약함 → 生(인성)·助(비겁)으로 보강
- 중화: 균형 → 조후(계절 기후)로 보정

판정 방식:
  지지의 정기(正氣)만 사용한 단순 버전. 위치별 가중치:
    월지 3.0 (계절 = 가장 강한 영향)
    일지 2.0 (배우자궁, 일간과 가장 가까움)
    시지 1.5
    년지 1.0
  천간(년·월·시)은 각 1.0
  일간 자신은 계산에서 제외
"""
from app.engine.elements import STEM_TO_ELEMENT, BRANCH_HIDDEN_STEMS, ELEMENT_NAMES

_BRANCH_WEIGHTS = {
    "year_pillar": 1.0,
    "month_pillar": 3.0,
    "day_pillar": 2.0,
    "hour_pillar": 1.5,
}


def _classify_relation(day_elem: str, target_elem: str) -> str:
    """
    일간 오행 대비 대상 오행의 관계 분류.

    support = 비겁(같음) 또는 인성(대상이 일간을 生)
    oppose  = 식상(일간이 대상 生), 재성(일간이 대상 剋), 관성(대상이 일간 剋)
    """
    if target_elem == day_elem:
        return "support"  # 비겁
    dm_idx = ELEMENT_NAMES.index(day_elem)
    tg_idx = ELEMENT_NAMES.index(target_elem)
    if (tg_idx + 1) % 5 == dm_idx:
        return "support"  # 인성 (target이 day master를 生)
    return "oppose"


def assess_day_master_strength(pillars: dict) -> dict:
    """
    4기둥의 신강/신약을 판정.

    반환:
      verdict:        "신강" | "중화" | "신약"
      support_score:  일간을 돕는 세력 점수
      oppose_score:   일간을 소모·억제하는 세력 점수
      support_ratio:  support / (support + oppose)
    """
    day_stem = pillars["day_pillar"][0]
    day_elem = STEM_TO_ELEMENT[day_stem]

    # AUTO-GENERATED by _fix_strength_hour_optional.py
    support = 0.0
    oppose = 0.0

    # 지지의 정기(첫 번째 지장간)로 판정
    for pos, weight in _BRANCH_WEIGHTS.items():
        pillar = pillars.get(pos, "")
        if not isinstance(pillar, str) or len(pillar) != 2:
            continue
        branch = pillar[1]
        hidden = BRANCH_HIDDEN_STEMS.get(branch, [])
        if not hidden:
            continue
        main_stem = hidden[0]
        target_elem = STEM_TO_ELEMENT[main_stem]
        if _classify_relation(day_elem, target_elem) == "support":
            support += weight
        else:
            oppose += weight

    # 천간 (일간 제외) 각 1.0
    for pos in ("year_pillar", "month_pillar", "hour_pillar"):
        pillar = pillars.get(pos, "")
        if not isinstance(pillar, str) or len(pillar) != 2:
            continue
        stem = pillar[0]
        target_elem = STEM_TO_ELEMENT[stem]
        if _classify_relation(day_elem, target_elem) == "support":
            support += 1.0
        else:
            oppose += 1.0

    total = support + oppose
    ratio = support / total if total else 0.5

    if ratio >= 0.6:
        verdict = "신강"
    elif ratio <= 0.4:
        verdict = "신약"
    else:
        verdict = "중화"

    return {
        "verdict": verdict,
        "support_score": round(support, 1),
        "oppose_score": round(oppose, 1),
        "support_ratio": round(ratio, 3),
    }