def load_json(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def save_json(path: Path, data: dict) -> None:
    payload = json.dumps(data, ensure_ascii=False, indent=2) + "\n"
    json.loads(payload)  # 유효성 검증
    path.write_text(payload, encoding="utf-8")


def main() -> int:
    print("=" * 60)
    print("[Phase 2-A2/5 — JA] year.json YEAR_THEME_CONTENT (배치 2)")
    print("=" * 60)

    if not JA_YEAR.exists():
        print(f"❌ {JA_YEAR} 없음")
        return 1

    data = load_json(JA_YEAR)
    ytc = data.get("YEAR_THEME_CONTENT")
    if not isinstance(ytc, dict):
        print("❌ YEAR_THEME_CONTENT 없음")
        return 1

    for key, variants in TRANSLATIONS.items():
        if len(variants) != 3:
            print(f"❌ {key}: variant 수 {len(variants)} (3이어야 함)")
            return 1
        ytc[key] = variants
        print(f"✅ {key}: {len(variants)} variants")

    save_json(JA_YEAR, data)
    print(f"\n✅ {JA_YEAR.name} 저장 완료")

    # ── 검증
    print("\n[verify]")
    data2 = load_json(JA_YEAR)
    ytc2 = data2["YEAR_THEME_CONTENT"]
    checks = [
        ("TEN_GOD_EATING_GOD", 0, "name", "豊かな創造の泉"),
        ("TEN_GOD_EATING_GOD", 2, "lean_into",
         "自分だけの独自の視点と表現を、継続的なロングフォームのコンテンツや作品として残すこと。"),
        ("TEN_GOD_HURTING_OFFICER", 0, "name", "革新と改革のアイコン"),
        ("TEN_GOD_HURTING_OFFICER", 2, "headline",
         "一年を通して、あなたは停滞した慣習を振り払い、時代に合った新しい道を創り出す人になります。"),
    ]
    ok = True
    for god, idx, field, expected in checks:
        actual = ytc2[god][idx][field]
        if actual == expected:
            print(f"  [OK] {god}[{idx}].{field}")
        else:
            print(f"  [ERR] {god}[{idx}].{field}:")
            print(f"       expected={expected!r}")
            print(f"       actual  ={actual!r}")
            ok = False

    # 이전 배치 회귀 방지
