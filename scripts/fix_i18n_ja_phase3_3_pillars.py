def load_json(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def save_json(path: Path, data: dict) -> None:
    payload = json.dumps(data, ensure_ascii=False, indent=2) + "\n"
    json.loads(payload)
    path.write_text(payload, encoding="utf-8")


def main() -> int:
    print("=" * 60)
    print("[Phase 3-3 — JA] core_pillars Fire/丙 (6 files)")
    print("=" * 60)

    if not JA_DIR.exists():
        print(f"❌ {JA_DIR} 없음")
        return 1

    written = []
    for key, ov in TRANSLATIONS.items():
        path = JA_DIR / f"{key}.json"
        if not path.exists():
            print(f"❌ {key}.json 없음")
            return 1
        data = load_json(path)
        if data.get("pillar") != key:
            print(f"❌ {key}.json::pillar 불일치 ({data.get('pillar')!r})")
            return 1
        old_name_trad = data.get("name_traditional", "")
        for k, v in ov.items():
            data[k] = v
        if "name_traditional" in data and data["name_traditional"] != old_name_trad:
            print(f"❌ {key}: name_traditional 손상")
            return 1
        save_json(path, data)
        print(f"✅ {key}: {ov['name']}")
        written.append(key)

    print(f"\n✅ {len(written)}개 파일 저장 완료")

    # ── 검증
    print("\n[verify]")
