def _has_kana(text: str) -> bool:
    return bool(text) and bool(KANA_RE.search(text))


def verify() -> bool:
    print("\n[verify] 각 파일 회귀방지 체크")
    ok = True
    for pillar, trans in TRANSLATIONS.items():
        fpath = JA / f"{pillar}.json"
        data = json.loads(fpath.read_text(encoding="utf-8"))
        checks = [("name", _has_kana(data.get("name", ""))),
                  ("hero", _has_kana(data.get("hero", "")))]
        for i, n in enumerate(data.get("narrative", [])):
            checks.append((f"narrative[{i}]", _has_kana(n)))
        for i, s in enumerate(data.get("shadows", [])):
            checks.append((f"shadows[{i}]", _has_kana(s)))
        for i, a in enumerate(data.get("advice", [])):
            checks.append((f"advice[{i}]", _has_kana(a)))
        bad = [n for n, p in checks if not p]
        if bad:
            print(f"  [ERR] {pillar}: 미포함 필드 {bad}")
            ok = False
        else:
            print(f"  [OK] {pillar}: {data['name']}")
    return ok


def main() -> int:
    print("=" * 60)
    print("[Phase 3-10] JA core_pillars 辛 (6 files) — core_pillars 60/60")
    print("=" * 60)
    written = 0
    for pillar, trans in TRANSLATIONS.items():
        fpath = JA / f"{pillar}.json"
        if not fpath.exists():
            print(f"❌ 파일 없음: {fpath}"); return 1
        data = json.loads(fpath.read_text(encoding="utf-8"))
        data.update(trans)
        payload = json.dumps(data, ensure_ascii=False, indent=2) + "\n"
        json.loads(payload)
        fpath.write_text(payload, encoding="utf-8")
        print(f"✅ {pillar}: {trans['name']}")
        written += 1
    print(f"\n저장 완료: {written}/{len(TRANSLATIONS)}")
    ok = verify()
    print("=" * 60)
    if not ok:
        print("❌ verify 실패"); return 1
    print("🎉 Phase 3-10 완료 — core_pillars 60/60 🏆")
    return 0


