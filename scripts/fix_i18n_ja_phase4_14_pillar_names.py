def _ja(s): return bool(s) and bool(KANA_RE.search(s))

def main():
    print("=" * 60); print("[Phase 4-14] pillar_names 60 entries"); print("=" * 60)
    if not JA.exists():
        # 없으면 생성
        JA.parent.mkdir(parents=True, exist_ok=True)
        data = {}
        print(f"📄 파일 새로 생성: {JA.name}")
    else:
        data = json.loads(JA.read_text(encoding="utf-8"))

    for hanzi, name, trad in PILLARS:
        data[hanzi] = {"name": name, "traditional": trad}

    payload = json.dumps(data, ensure_ascii=False, indent=2) + "\n"
    json.loads(payload)
    JA.write_text(payload, encoding="utf-8")
    print(f"✅ {len(PILLARS)} 기둥 저장")

    print("\n[verify]")
    ok = True
    for hanzi, name, trad in PILLARS:
        d = data[hanzi]
        if not _ja(d.get("name", "")): print(f"  [ERR] {hanzi}.name"); ok = False
        if not _ja(d.get("traditional", "")): print(f"  [ERR] {hanzi}.traditional"); ok = False
    if ok and len(data) == 60:
        print(f"  [OK] pillar_names 100% JA (60/60) 🏆")
    print("=" * 60)
    return 0 if (ok and len(data) == 60) else 1

if __name__ == "__main__": sys.exit(main())