def _has_kana(text: str) -> bool:
    return bool(text) and bool(KANA_RE.search(text))


def verify() -> bool:
    print("\n[verify] 각 파일 회귀방지 체크")
    ok = True
    for pillar, trans in TRANSLATIONS.items():
        fpath = JA / f"{pillar}.json"
        if not fpath.exists():
            print(f"  [ERR] {pillar}: 파일 없음 ({fpath})")
            ok = False
            continue
        try:
            data = json.loads(fpath.read_text(encoding="utf-8"))
        except Exception as e:
            print(f"  [ERR] {pillar}: JSON 로드 실패 ({e})")
            ok = False
            continue

        checks = []
        checks.append(("name", _has_kana(data.get("name", ""))))
        checks.append(("hero", _has_kana(data.get("hero", ""))))
        for i, n in enumerate(data.get("narrative", [])):
            checks.append((f"narrative[{i}]", _has_kana(n)))
        for i, s in enumerate(data.get("shadows", [])):
            checks.append((f"shadows[{i}]", _has_kana(s)))
        for i, a in enumerate(data.get("advice", [])):
            checks.append((f"advice[{i}]", _has_kana(a)))
        for i, k in enumerate(data.get("keywords", [])):
            checks.append((f"keywords[{i}]", _has_kana(k)))

        bad = [name for name, passed in checks if not passed]
        if bad:
            print(f"  [ERR] {pillar}: 일본어 미포함 필드 {bad}")
            ok = False
        else:
            print(f"  [OK] {pillar}: {data['name']}")
    return ok


